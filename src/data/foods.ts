export const localFoods: FoodItem[] = rows.map(([name, kcal, protein, fat, carbs, portion]) => ({
  name,
  kcal,
  protein,
  fat,
  carbs,
  portion,
  source: 'local',
}))

const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').trim()

export function searchLocal(query: string, limit = 12): FoodItem[] {
  const q = norm(query)
  if (!q) return []
  const words = q.split(/\s+/)
  return localFoods
    .map((f) => {
      const name = norm(f.name)
      if (!words.every((w) => name.includes(w))) return null
      const score = name.startsWith(q) ? 0 : name.includes(q) ? 1 : 2
      return { f, score }
    })
    .filter((x): x is { f: FoodItem; score: number } => x !== null)
    .sort((a, b) => a.score - b.score || a.f.name.length - b.f.name.length)
    .slice(0, limit)
    .map((x) => x.f)
}
